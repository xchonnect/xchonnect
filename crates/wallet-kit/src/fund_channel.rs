    #[test]
    fn addresses_follow_bech32m() {
        let v = vectors();
        for case in v["cases"].as_array().unwrap() {
            let address = case["address"].as_str().unwrap();
            let (prefix, ph) = decode_address(address).unwrap();
            assert_eq!(prefix, case["prefix"].as_str().unwrap());
            assert_eq!(hex::encode(ph), case["depositPuzzleHash"].as_str().unwrap());
            // Upper case is the same address; mixed case is not an address.
            assert_eq!(
                decode_address(&address.to_ascii_uppercase()),
                Some((prefix, ph))
            );
            let mixed = format!("{}{}", address[..1].to_ascii_uppercase(), &address[1..]);
            assert_eq!(decode_address(&mixed), None);
        }
        // A bech32 (not bech32m) checksum is refused: BIP-173's example.
        assert_eq!(
            decode_address("bc1qw508d6qejxtdg4y5r3zarvary0c5xw7kv8f3t4"),
            None
        );
    }

