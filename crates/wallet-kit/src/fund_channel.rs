use xchonnect_core::rpc::codes;

/// The method name.
pub const FUND_CHANNEL: &str = "chia_fundChannel";

/// The tree hash of the paychan v1 module (`paychan_v1.clsp`). Every deposit address depends
/// on it: a new module is a new version, never this one changed.
pub const PAYCHAN_V1_MOD_HASH: [u8; 32] = [
    0xa3, 0xdc, 0x8f, 0x11, 0x92, 0x5b, 0x52, 0xab, 0x89, 0xad, 0x8a, 0x06, 0x4a, 0x97, 0xf3, 0x50,
    0xdd, 0x7b, 0xf9, 0x8c, 0xbd, 0x09, 0x94, 0x51, 0x13, 0xd2, 0x8c, 0x65, 0x19, 0x78, 0xba, 0x74,
];

/// The longest channel timeout a wallet funds: 31 days, in seconds (spec 9.1, check 4).
pub const MAX_CHANNEL_TIMEOUT: u64 = 2_678_400;

/// The listing format this check reads.
pub const LISTING_VERSION: u32 = 1;

/// The tag of the operator's listing signature: `sha256tree(("paychan1-listing" listing))`.
pub const TAG_LISTING: &[u8] = b"paychan1-listing";

/// The operator's listing, as paychan v1 defines it. Fields this version does not know are
/// ignored; a missing field makes the listing malformed.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Listing {
    /// `1`.
    pub version: u32,
    /// The key that signed the listing, hex (48 bytes).
    pub operator_pk: String,
    /// The operator's OpenAI-compatible base URL.
    pub endpoint: String,
    /// `mainnet` or `testnet11`.
    pub network: String,
    /// Unix seconds.
    pub issued: u64,
    /// Unix seconds; the listing opens only before it.
    pub expires: u64,
    /// How a channel to this operator is made and paid.
    pub payment: ListedTerms,
    /// Labels, never proofs.
    pub privacy: Privacy,
    /// What the operator sells.
    pub models: Vec<ListedModel>,
}

/// The listing's payment terms: the receiver's half of the channel.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ListedTerms {
    /// The CAT the lanes hold (TAIL hash), hex.
    pub asset_id: String,
    /// The operator's statement of the CAT's decimals (the wallet uses its own).
    pub decimals: u8,
    /// The receiver's payout puzzle hash, hex (32 bytes).
    pub receiver_ph: String,
    /// The receiver's close key, hex (48 bytes).
    pub receiver_pk: String,
    /// Seconds a lane coin must exist before anyone may refund it.
    pub timeout: u64,
    /// A payment's expiry is at least this many seconds ahead.
    pub min_expiry_s: u64,
    /// And at most this many.
    pub max_expiry_s: u64,
}

/// What the operator says happens to a prompt.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Privacy {
    /// The operator stores prompts or answers.
    pub operator_keeps_prompts: bool,
    /// `deny` or `unknown`.
    pub upstream_data_collection: String,
}

/// One model the operator sells.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ListedModel {
    /// The model's name.
    pub id: String,
    /// Tokens.
    pub context_length: Option<u64>,
    /// Nano-mojos of the CAT per token and per request.
    pub price: ListedPrice,
    /// The most one request costs, in mojos of the CAT.
    pub max_cost: u64,
    /// What backs the token count, a label.
    pub evidence: String,
}

/// Prices in nano-mojos (10^-9 mojo) of the channel's CAT.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct ListedPrice {
    /// Per input token.
    pub input: u64,
    /// Per output token.
    pub output: u64,
    /// Per request.
    pub request: u64,
}

/// The five values a paychan v1 channel is curried with.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ChannelValues {
    /// The agent's channel key: it signs the totals the operator may claim.
    pub channel_pk: PublicKey,
    /// The user's p2 puzzle hash: refunds and close rests go only here.
    pub refund_puzzle_hash: Bytes32,
    /// The operator's payout puzzle hash: claims go only here.
    pub receiver_puzzle_hash: Bytes32,
    /// The operator's close key.
    pub receiver_pk: PublicKey,
    /// Seconds a lane coin must exist before anyone may refund it.
    pub timeout: u64,
}

impl ChannelValues {
    /// The channel's deposit puzzle hash: the inner puzzle hash the CAT is sent to (`LANE` nil,
    /// `CLAIMED` 0). Curry 1 makes `SELF_HASH`; curry 2 applies the state to it.
    pub fn deposit_puzzle_hash(&self) -> Bytes32 {
        let self_hash = curry_tree_hash(
            TreeHash::new(PAYCHAN_V1_MOD_HASH),
            &[
                tree_hash_atom(&self.channel_pk.to_bytes()),
                tree_hash_atom(self.refund_puzzle_hash.as_ref()),
                tree_hash_atom(self.receiver_puzzle_hash.as_ref()),
                tree_hash_atom(&self.receiver_pk.to_bytes()),
                tree_hash_atom(&clvm_int(self.timeout)),
            ],
        );
        let nil = tree_hash_atom(&[]);
        curry_tree_hash(
            self_hash,
            &[tree_hash_atom(&self_hash.to_bytes()), nil, nil],
        )
        .into()
    }
}

/// A request that passed checks 1 to 6: everything the prompt shows and the wallet keeps.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct FundChannel {
    /// The channel's five values.
    pub channel: ChannelValues,
    /// The CAT the deposit sends (the listing's `payment.asset_id`).
    pub asset_id: Bytes32,
    /// CAT mojos to deposit.
    pub amount: u64,
    /// The agent's fee, XCH mojos, if it sent one.
    pub fee: Option<u64>,
    /// The verified listing.
    pub listing: Listing,
    /// The listing exactly as received (the signed bytes) and its signature: keep both, so
    /// the listing can be verified again later.
    pub listing_text: String,
    /// The listing's signature, hex as received.
    pub listing_signature: String,
    /// The operator key that signed the listing.
    pub operator_pk: PublicKey,
    /// The inner puzzle hash the CAT is sent to.
    pub deposit_puzzle_hash: Bytes32,
    /// The same wrapped in the CAT2 layer of `asset_id`: the deposit coin's puzzle hash.
    pub deposit_cat_puzzle_hash: Bytes32,
    /// The deposit address (the agent's, equal to the derived one).
    pub address: String,
    /// The earliest time the deposit can be refunded: `now + timeout` (each claim restarts
    /// the clock of the lane it pays from).
    pub refund_not_before: u64,
}

impl FundChannel {
    /// The intent of the wallet-built send (spec 9.1): exactly `amount` of the CAT to the
    /// deposit puzzle hash, nothing to anyone else, and the fee the wallet chose.
    pub fn intent(&self, wallet_fee: u64) -> Intent {
        Intent {
            kind: None,
            recipients: Some(vec![RecipientClaim {
                asset: AssetId::Cat(self.asset_id),
                puzzle_hash: self.deposit_puzzle_hash,
                amount: self.amount,
            }]),
            fee: Some(wallet_fee),
            net: None,
        }
    }
}

/// Runs checks 1 to 6 of spec 9.1 "Channel funding" on a `chia_fundChannel` request's params
/// (JSON text), in order, and returns the first refusal: 4000 `invalid_params` (1), 4001
/// `listing_invalid` (2), `wrong_network` (3), `timeout_too_long` (4), `refund_not_own` (5),
/// `address_mismatch` (6). `owns` says whether a puzzle hash is one of the wallet's own p2
/// puzzle hashes; `now` is the wallet's clock, unix seconds.
pub fn check_fund_channel(
    params_json: &str,
    network: &Network,
    now: u64,
    owns: impl Fn(&Bytes32) -> bool,
) -> Result<FundChannel, RpcError> {
    let invalid = || RpcError::new(codes::INVALID_PARAMS, "invalid params");
    let refused =
        |reason: &str| RpcError::new(codes::UNAUTHORIZED, "unauthorized").with_reason(reason);

    // 1. The params' shape.
    let params: Value = serde_json::from_str(params_json).map_err(|_| invalid())?;
    let channel_pk = params
        .get("channelPk")
        .and_then(Value::as_str)
        .and_then(public_key)
        .filter(|pk| !pk.is_inf())
        .ok_or_else(invalid)?;
    let refund_puzzle_hash = params
        .get("refundPuzzleHash")
        .and_then(Value::as_str)
        .and_then(bytes32)
        .ok_or_else(invalid)?;
    let signed = params.get("listing").ok_or_else(invalid)?;
    let listing_text = signed
        .get("listing")
        .and_then(Value::as_str)
        .ok_or_else(invalid)?;
    let listing_signature = signed
        .get("signature")
        .and_then(Value::as_str)
        .ok_or_else(invalid)?;
    let amount = params
        .get("amount")
        .and_then(amount_of)
        .filter(|a| *a > 0)
        .ok_or_else(invalid)?;
    let fee = match params.get("fee") {
        None | Some(Value::Null) => None,
        Some(v) => Some(amount_of(v).ok_or_else(invalid)?),
    };
    let address = params
        .get("address")
        .and_then(Value::as_str)
        .ok_or_else(invalid)?;
    let (prefix, address_ph) = decode_address(address).ok_or_else(invalid)?;

    // 2. The listing opens: its own key signed it, version 1, unexpired.
    let (listing, operator_pk) = open_listing(listing_text, listing_signature, now)
        .ok_or_else(|| refused("listing_invalid"))?;
    let terms = &listing.payment;
    let (receiver_puzzle_hash, receiver_pk, asset_id) = match (
        bytes32(&terms.receiver_ph),
        public_key(&terms.receiver_pk),
        bytes32(&terms.asset_id),
    ) {
        (Some(ph), Some(pk), Some(id)) => (ph, pk, id),
        _ => return Err(refused("listing_invalid")),
    };

    // 3. The listing's network is the wallet's.
    if listing.network != network.chain_id() {
        return Err(refused("wrong_network"));
    }

    // 4. A timeout the user can wait for.
    if terms.timeout == 0 || terms.timeout > MAX_CHANNEL_TIMEOUT {
        return Err(refused("timeout_too_long"));
    }

    // 5. Refunds come back to the wallet.
    if !owns(&refund_puzzle_hash) {
        return Err(refused("refund_not_own"));
    }

    // 6. The agent's address is the one these values make, on this network.
    let channel = ChannelValues {
        channel_pk,
        refund_puzzle_hash,
        receiver_puzzle_hash,
        receiver_pk,
        timeout: terms.timeout,
    };
    let deposit_puzzle_hash = channel.deposit_puzzle_hash();
    if prefix != address_prefix(network) || address_ph != deposit_puzzle_hash {
        return Err(refused("address_mismatch"));
    }

    Ok(FundChannel {
        channel,
        asset_id,
        amount,
        fee,
        deposit_cat_puzzle_hash: CatArgs::curry_tree_hash(
            asset_id,
            TreeHash::from(deposit_puzzle_hash),
        )
        .into(),
        deposit_puzzle_hash,
        address: encode_address(&prefix, &deposit_puzzle_hash),
        refund_not_before: now.saturating_add(terms.timeout),
        operator_pk,
        listing_text: listing_text.to_owned(),
        listing_signature: listing_signature.to_owned(),
        listing,
    })
}

/// `sha256tree(("paychan1-listing" listing_json))`: what the operator key signs (BLS
/// augmented scheme, as every Chia signature).
pub fn listing_message(listing_json: &str) -> Bytes32 {
    let nil = tree_hash_atom(&[]);
    tree_hash_pair(
        tree_hash_atom(TAG_LISTING),
        tree_hash_pair(tree_hash_atom(listing_json.as_bytes()), nil),
    )
    .into()
}

/// The listing and its operator key, when that key signed exactly `text`, the version is 1
/// and it has not expired at `now`.
fn open_listing(text: &str, signature: &str, now: u64) -> Option<(Listing, PublicKey)> {
    let listing: Listing = serde_json::from_str(text).ok()?;
    if listing.version != LISTING_VERSION {
        return None;
    }
    let key = public_key(&listing.operator_pk)?;
    let signature: [u8; 96] = decode_hex(signature)?.try_into().ok()?;
    let signature = Signature::from_bytes(&signature).ok()?;
    if !chia_bls::verify(&signature, &key, listing_message(text)) || listing.expires <= now {
        return None;
    }
    Some((listing, key))
}

/// The address prefix of the wallet's network: `xch` on mainnet, `txch` elsewhere.
pub fn address_prefix(network: &Network) -> String {
    match network {
        Network::Mainnet => "xch".to_owned(),
        _ => "txch".to_owned(),
    }
}

fn public_key(text: &str) -> Option<PublicKey> {
    let bytes: [u8; 48] = decode_hex(text)?.try_into().ok()?;
    PublicKey::from_bytes(&bytes).ok()
}

fn bytes32(text: &str) -> Option<Bytes32> {
    let bytes: [u8; 32] = decode_hex(text)?.try_into().ok()?;
    Some(Bytes32::new(bytes))
}

/// An amount as a decimal string or a JSON integer (spec 9.1).
fn amount_of(v: &Value) -> Option<u64> {
    match v {
        Value::Number(n) => n.as_u64(),
        Value::String(s)
            if !s.is_empty() && s.len() <= 20 && s.bytes().all(|b| b.is_ascii_digit()) =>
        {
            s.parse().ok()
        }
        _ => None,
    }
}

/// A CLVM integer atom: big-endian two's complement, shortest form (0 is the empty atom).
fn clvm_int(v: u64) -> Vec<u8> {
    let bytes = v.to_be_bytes();
    let first = bytes.iter().position(|b| *b != 0).unwrap_or(bytes.len());
    let mut out: Vec<u8> = bytes.get(first..).unwrap_or_default().to_vec();
    if out.first().is_some_and(|b| b & 0x80 != 0) {
        out.insert(0, 0);
    }
    out
}

const CHARSET: &[u8; 32] = b"qpzry9x8gf2tvdw0s3jn54khce6mua7l";
const BECH32M: u32 = 0x2bc8_30a3;

fn polymod(values: impl IntoIterator<Item = u8>) -> u32 {
    const GEN: [u32; 5] = [
        0x3b6a_57b2,
        0x2650_8e6d,
        0x1ea1_19fa,
        0x3d42_33dd,
        0x2a14_62b3,
    ];
    let mut chk: u32 = 1;
    for v in values {
        let top = chk >> 25;
        chk = ((chk & 0x01ff_ffff) << 5) ^ u32::from(v);
        for (i, g) in GEN.iter().enumerate() {
            if (top >> i) & 1 == 1 {
                chk ^= g;
            }
        }
    }
    chk
}

fn hrp_expand(hrp: &[u8]) -> Vec<u8> {
    hrp.iter()
        .map(|c| c >> 5)
        .chain([0])
        .chain(hrp.iter().map(|c| c & 31))
        .collect()
}

/// A puzzle hash as a bech32m address (`xch1…`, `txch1…`), as Chia encodes them.
pub fn encode_address(prefix: &str, puzzle_hash: &Bytes32) -> String {
    let mut data = Vec::with_capacity(58);
    let (mut acc, mut bits) = (0u32, 0u32);
    for b in puzzle_hash.as_ref() {
        acc = (acc << 8) | u32::from(*b);
        bits += 8;
        while bits >= 5 {
            bits -= 5;
            data.push(((acc >> bits) & 31) as u8);
        }
    }
    if bits > 0 {
        data.push(((acc << (5 - bits)) & 31) as u8);
    }
    let check = polymod(
        hrp_expand(prefix.as_bytes())
            .into_iter()
            .chain(data.iter().copied())
            .chain([0; 6]),
    ) ^ BECH32M;
    data.extend((0..6).map(|i| ((check >> (5 * (5 - i))) & 31) as u8));
    let mut out = String::with_capacity(prefix.len() + 1 + data.len());
    out.push_str(prefix);
    out.push('1');
    out.extend(
        data.iter()
            .filter_map(|d| CHARSET.get(usize::from(*d)).map(|c| char::from(*c))),
    );
    out
}

/// A bech32m address with a 32-byte payload: its prefix (lower case) and puzzle hash. `None`
/// for anything else: another checksum (bech32), mixed case, a payload of another length,
/// non-zero padding.
pub fn decode_address(address: &str) -> Option<(String, Bytes32)> {
    if address.len() > 90 || !address.bytes().all(|b| (33..=126).contains(&b)) {
        return None;
    }
    let lower = address.to_ascii_lowercase();
    if lower != address && address.to_ascii_uppercase() != address {
        return None;
    }
    let (hrp, data) = lower.rsplit_once('1')?;
    if hrp.is_empty() || data.len() < 6 {
        return None;
    }
    let values: Vec<u8> = data
        .bytes()
        .map(|c| CHARSET.iter().position(|x| *x == c).map(|p| p as u8))
        .collect::<Option<_>>()?;
    if polymod(
        hrp_expand(hrp.as_bytes())
            .into_iter()
            .chain(values.iter().copied()),
    ) != BECH32M
    {
        return None;
    }
    let payload = values.get(..values.len() - 6)?;
    let (mut acc, mut bits, mut bytes) = (0u32, 0u32, Vec::with_capacity(32));
    for v in payload {
        acc = ((acc << 5) | u32::from(*v)) & 0xfff;
        bits += 5;
        if bits >= 8 {
            bits -= 8;
            bytes.push(((acc >> bits) & 0xff) as u8);
        }
    }
    if bits >= 5 || (acc & ((1 << bits) - 1)) != 0 {
        return None;
    }
    let ph: [u8; 32] = bytes.try_into().ok()?;
    Some((hrp.to_owned(), Bytes32::new(ph)))
}

#[cfg(test)]
