    use super::*;
    use chia_bls::{SecretKey, sign};
    use proptest::prelude::*;

    const VECTORS: &str = include_str!(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../docs/spec/vectors/fund_channel.json"
    ));
    /// After the vectors' `issued`, before their `expires`.
    const NOW: u64 = 1_800_000_001;

    fn vectors() -> Value {
        serde_json::from_str(VECTORS).unwrap()
    }

    fn network(name: &str) -> Network {
        match name {
            "mainnet" => Network::Mainnet,
            _ => Network::Testnet11,
        }
    }

    fn params(case: &Value) -> Value {
        serde_json::json!({
            "channelPk": format!("0x{}", case["channelPk"].as_str().unwrap()),
            "refundPuzzleHash": format!("0x{}", case["refundPuzzleHash"].as_str().unwrap()),
            "listing": case["listing"],
            "amount": "1000",
            "address": case["address"],
        })
    }

    fn check_case(case: &Value, p: &Value, now: u64) -> Result<FundChannel, RpcError> {
        let refund = bytes32(case["refundPuzzleHash"].as_str().unwrap()).unwrap();
        check_fund_channel(
            &p.to_string(),
            &network(case["network"].as_str().unwrap()),
            now,
            |ph| *ph == refund,
        )
    }

    fn reason(e: &RpcError) -> (i64, String) {
        let data: Value = e
            .data
            .as_deref()
            .map(|d| serde_json::from_str(d).unwrap())
            .unwrap_or(Value::Null);
        (e.code, data["reason"].as_str().unwrap_or("").to_owned())
    }

    #[test]
